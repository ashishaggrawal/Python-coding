# Given two numbers a and b, print the result of every arithmetic operator.
# Input: a = 7, b = 2
# Output:
# Addition: 9
# Subtraction: 5
# Multiplication: 14
# Division: 3.5
# Floor Division: 3
# Modulus: 1
# Power: 49

a = int(input("Enter a: "))
b = int(input("Enter b: "))

print("Addition:", a + b)
print("Subtraction:", a - b)
print("Multiplication:", a * b)
print("Division:", a / b)
print("Floor Division:", a // b)
print("Modulus:", a % b)
print("Power:", a ** b)
