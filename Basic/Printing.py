# Practice the different ways to use print().
# Output:
# Hello Python
# Hello-Python
# Hello Python on the same line
# 10 + 20 = 30

print("Hello", "Python")             # values are separated by a space by default
print("Hello", "Python", sep="-")    # sep changes the separator
print("Hello Python", end=" ")       # end changes what comes after (default is a new line)
print("on the same line")
print(10, "+", 20, "=", 10 + 20)
